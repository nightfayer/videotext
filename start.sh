#!/bin/bash
# Скрипт автоматического обновления, пересборки и запуска бота
echo "🛑 Остановка старого контейнера..."
docker compose down

echo "🚀 Пересборка и запуск свежего контейнера..."
docker compose up -d

echo "📊 Подключение к живым логам бота (Ctrl+C для выхода из логов):"
docker compose logs -f
